#!/usr/bin/env python3
"""Write the run lists for run_sa.sh (fixed before any result is read).

    make_runs_sa.py adaptive > runs_adaptive.txt   # Part 1 + the adaptive half of Part 2
    make_runs_sa.py grid     > runs_grid.txt       # fixed-configuration grid

Both traces at boot delay 180 s (SWIM run index 3 = WorldCup, 8 = ClarkNet),
seed-sets 0-9. Labels are <trace>_<cell>_s<seed>; table_sa.py groups on them.

adaptive: doing nothing (Static with no targets: 3 servers, dimmer 0.9),
          SWIM's Reactive and Reactive2, Stevens's PLA-SDP port with its own
          utility (pladapt), and the same planner with SEAMS 2017A as its
          planning utility in three variants of the M/M/c's inputs
          (seams2017a is the primary; see README).
grid:     Static at servers 1..12 x dimmer k/9, k = 0..9, set at t = 0 and held.
"""

import sys

TRACES = {"wc": 3, "ck": 8}
SEEDS = range(10)
ADAPTIVE = [
    ("nothing", "Static", ""),
    ("reactive", "Reactive", ""),
    ("reactive2", "Reactive2", ""),
    ("pladapt", "pladapt", ""),
    ("seams", "pladapt_seams2017a", ""),
    ("seamsmaxrate", "pladapt_seams2017a_maxrate", ""),
    ("seamsstevensrt", "pladapt_seams2017a_stevensrt", ""),
]


def main() -> int:
    what = sys.argv[1]
    print("# label config run-index seed-set [settings]   (generated by make_runs_sa.py "
          f"{what})")
    for trace, run in TRACES.items():
        if what == "adaptive":
            for cell, config, extra in ADAPTIVE:
                for s in SEEDS:
                    print(f"{trace}_{cell}_s{s:02d} {config} {run} {s} {extra}".rstrip())
        elif what == "grid":
            for srv in range(1, 13):
                for k in range(10):
                    for s in SEEDS:
                        print(f"{trace}_fixed_srv{srv:02d}_dim{k}_s{s:02d} Static {run} {s} "
                              f"**.adaptationManager.servers={srv} "
                              f"**.adaptationManager.dimmer={k / 9:.12f}")
        else:
            raise SystemExit("usage: make_runs_sa.py adaptive|grid")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
